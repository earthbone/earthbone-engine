#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

//! Property based tests over generated load orders, the first commit of
//! `TEST_PLAN.md` phase 2.
//!
//! The rules the engine claims are simple to state and easy to break by
//! accident, which is what makes them worth a generator rather than a handful
//! of examples: the last file to write a form wins, a round trip through bytes
//! changes nothing, a runtime FormID is the file's slot over the object, and
//! the cell index agrees with where the placements actually went.
//!
//! The oracle for the cell property is the plan the generator followed, not a
//! second scan of the same records. A re-scan would re-implement `CellIndex`
//! and agree with it for the same wrong reason, so the expectation is built
//! while the files are emitted and compared afterwards.
//!
//! Every plugin is serialised and parsed back before it reaches the order, so
//! the parser sees generated bytes on every case rather than a model handed
//! straight to it.

mod common;

use proptest::prelude::*;
use soe_esm::{
    plugin::flags, tag, Entry, FileHeader, GlobalFormId, Group, GroupKind, LoadOrder, Plugin,
    Record,
};
use std::collections::{BTreeMap, BTreeSet};

const KRATE: &str = "soe-esm";
const FILE: &str = "prop_load_order";

/// Objects live above the header ids the format reserves.
const FIRST_OBJECT: u32 = 0x800;
/// A file's own records are written with an index past its master list.
const OWN_PREFIX: u32 = 0x0100_0000;
const FIRST_OWN: u32 = 0x900;

/// What one patch does to the shared objects, one slot per object.
/// `None` leaves it alone, `Some(deleted)` writes it.
type Writes = Vec<Option<bool>>;

/// A patch: what it writes, how many records of its own it defines, and
/// whether it loads as a light plugin.
#[derive(Debug, Clone)]
struct Patch {
    writes: Writes,
    own: usize,
    light: bool,
}

fn patch_strategy(objects: usize) -> impl Strategy<Value = Patch> {
    (
        proptest::collection::vec(proptest::option::of(any::<bool>()), objects),
        0usize..=2,
        any::<bool>(),
    )
        .prop_map(|(writes, own, light)| Patch { writes, own, light })
}

fn order_strategy() -> impl Strategy<Value = (usize, Vec<Patch>)> {
    (1usize..=5).prop_flat_map(|objects| {
        proptest::collection::vec(patch_strategy(objects), 1..=4)
            .prop_map(move |patches| (objects, patches))
    })
}

fn edid_of(record: &Record) -> String {
    record.editor_id().unwrap_or_default()
}

/// Serialise, parse, serialise again, and fail the case if the bytes moved.
/// Returns the parsed plugin so the caller builds its order from bytes the
/// parser produced rather than from the model.
fn round_tripped(plugin: &Plugin) -> Result<Plugin, TestCaseError> {
    let first = plugin.to_bytes();
    let parsed = Plugin::parse(&first)
        .map_err(|e| TestCaseError::fail(format!("generated plugin did not parse: {e}")))?;
    let second = parsed.to_bytes();
    if first != second {
        let at = first
            .iter()
            .zip(second.iter())
            .position(|(a, b)| a != b)
            .unwrap_or_else(|| first.len().min(second.len()));
        return Err(TestCaseError::fail(format!(
            "round trip changed the bytes at offset {at}, {} in and {} out. Replay: {}",
            first.len(),
            second.len(),
            common::repro(KRATE, FILE, "a_plugin_survives_a_round_trip_through_bytes")
        )));
    }
    Ok(parsed)
}

fn shared_master(objects: usize) -> Plugin {
    let mut p = Plugin::new(FileHeader {
        flags: flags::MASTER,
        ..Default::default()
    });
    for o in 0..objects {
        p.push_top(Record::new(tag::STAT, FIRST_OBJECT + o as u32).zsub(tag::EDID, "f0"));
    }
    p
}

fn patch_plugin(index: usize, patch: &Patch) -> Plugin {
    let mut header = FileHeader {
        masters: vec!["Master.esm".into()],
        ..Default::default()
    };
    if patch.light {
        header.flags |= flags::LIGHT_MASTER;
    }
    let mut p = Plugin::new(header);
    let label = format!("f{}", index + 1);
    for (o, action) in patch.writes.iter().enumerate() {
        if let Some(deleted) = action {
            let mut record =
                Record::new(tag::STAT, FIRST_OBJECT + o as u32).zsub(tag::EDID, &label);
            if *deleted {
                record = record.with_flags(flags::DELETED);
            }
            p.push_top(record);
        }
    }
    for own in 0..patch.own {
        p.push_top(
            Record::new(tag::STAT, OWN_PREFIX | (FIRST_OWN + own as u32))
                .zsub(tag::EDID, &format!("{label}own{own}")),
        );
    }
    p
}

/// Builds the order and returns it alongside the slot each file landed in.
fn build_order(
    objects: usize,
    patches: &[Patch],
) -> Result<(LoadOrder, Vec<(bool, u16)>), TestCaseError> {
    let mut order = LoadOrder::new();
    let mut slots = Vec::new();
    let master = round_tripped(&shared_master(objects))?;
    order
        .add("Master.esm", master)
        .map_err(|e| TestCaseError::fail(format!("master did not load: {e}")))?;
    slots.push((false, 0u16));

    let (mut regular, mut light) = (1u16, 0u16);
    for (i, patch) in patches.iter().enumerate() {
        let plugin = round_tripped(&patch_plugin(i, patch))?;
        order
            .add(&format!("Patch{i}.esp"), plugin)
            .map_err(|e| TestCaseError::fail(format!("Patch{i} did not load: {e}")))?;
        if patch.light {
            slots.push((true, light));
            light += 1;
        } else {
            slots.push((false, regular));
            regular += 1;
        }
    }
    Ok((order, slots))
}

proptest! {
    #![proptest_config(ProptestConfig { cases: 192, ..ProptestConfig::default() })]

    /// The last file to write a form is the one the order reports, and the
    /// override list holds every file that wrote it, in order.
    #[test]
    fn the_last_file_to_write_a_form_wins((objects, patches) in order_strategy()) {
        let (order, _) = build_order(objects, &patches)?;

        // The plan is the oracle: walk it the way a reader would and keep the
        // last writer per object.
        let mut expected: Vec<(usize, bool, usize)> = (0..objects).map(|_| (0, false, 1)).collect();
        for (i, patch) in patches.iter().enumerate() {
            for (o, action) in patch.writes.iter().enumerate() {
                if let Some(deleted) = action {
                    expected[o] = (i + 1, *deleted, expected[o].2 + 1);
                }
            }
        }

        for (o, (writer, deleted, writes)) in expected.iter().enumerate() {
            let id = GlobalFormId { file: 0, object: FIRST_OBJECT + o as u32 };
            let winner = order.winner(id).ok_or_else(|| TestCaseError::fail(format!(
                "object {o} vanished from the order. Replay: {}",
                common::repro(KRATE, FILE, "the_last_file_to_write_a_form_wins")
            )))?;
            prop_assert_eq!(
                edid_of(winner),
                format!("f{writer}"),
                "object {} should come from file {}. Replay: {}",
                o, writer, common::repro(KRATE, FILE, "the_last_file_to_write_a_form_wins")
            );
            prop_assert_eq!(
                winner.is_deleted(), *deleted,
                "object {} deletion flag. Replay: {}",
                o, common::repro(KRATE, FILE, "the_last_file_to_write_a_form_wins")
            );
            prop_assert_eq!(
                order.overrides(id).len(), *writes,
                "object {} override count. Replay: {}",
                o, common::repro(KRATE, FILE, "the_last_file_to_write_a_form_wins")
            );
        }
    }

    /// Serialising a plugin and parsing it back produces the same bytes a
    /// second time. `round_tripped` does the work, this case exists so the
    /// property has a name of its own in the report.
    #[test]
    fn a_plugin_survives_a_round_trip_through_bytes((objects, patches) in order_strategy()) {
        round_tripped(&shared_master(objects))?;
        for (i, patch) in patches.iter().enumerate() {
            round_tripped(&patch_plugin(i, patch))?;
        }
    }

    /// A runtime FormID is the file's slot over the object, with light files
    /// packed behind `0xFE` in twelve bits instead of a whole byte.
    #[test]
    fn a_runtime_form_id_is_the_slot_over_the_object((objects, patches) in order_strategy()) {
        let (order, slots) = build_order(objects, &patches)?;

        for (file, (light, slot)) in slots.iter().enumerate() {
            let object = if file == 0 { FIRST_OBJECT } else { FIRST_OWN };
            let id = GlobalFormId { file: file as u16, object };
            let want = if *light {
                0xFE00_0000 | (u32::from(*slot) << 12) | (object & 0xFFF)
            } else {
                (u32::from(*slot) << 24) | (object & 0x00FF_FFFF)
            };
            prop_assert_eq!(
                order.runtime_id(id), want,
                "file {} slot arithmetic. Replay: {}",
                file, common::repro(KRATE, FILE, "a_runtime_form_id_is_the_slot_over_the_object")
            );
        }

        // A file's own record resolves to that file, which is what makes the
        // slot arithmetic above reachable at all.
        for (i, patch) in patches.iter().enumerate() {
            for own in 0..patch.own {
                let raw = OWN_PREFIX | (FIRST_OWN + own as u32);
                let id = order.resolve(i + 1, raw);
                prop_assert_eq!(
                    id.file, (i + 1) as u16,
                    "Patch{} own record {} resolved to file {}. Replay: {}",
                    i, own, id.file,
                    common::repro(KRATE, FILE, "a_runtime_form_id_is_the_slot_over_the_object")
                );
            }
        }
    }
}

// ----- the cell index against the plan that placed the references -----

const CELL_A: u32 = 0x600;
const CELL_B: u32 = 0x601;
const FIRST_REF: u32 = 0x700;

/// Where one patch moves each reference, one slot per reference.
/// `None` leaves it where it was, `Some((cell, deleted))` re-places it.
type Moves = Vec<Option<(bool, bool)>>;

fn cell_order_strategy() -> impl Strategy<Value = (usize, Vec<Moves>)> {
    (1usize..=4).prop_flat_map(|refs| {
        proptest::collection::vec(
            proptest::collection::vec(proptest::option::of((any::<bool>(), any::<bool>())), refs),
            1..=3,
        )
        .prop_map(move |patches| (refs, patches))
    })
}

/// Builds a plugin holding two interior cells and the placements given, one
/// entry per cell. A cell with no placements is still written, because a patch
/// that empties a cell has to override the cell record too.
fn cells_plugin(
    header: FileHeader,
    label: &str,
    placed: &BTreeMap<u32, Vec<(u32, bool)>>,
) -> Plugin {
    let mut p = Plugin::new(header);
    let mut sub = Group::new(GroupKind::InteriorSubBlock(0));
    for (cell_id, refs) in placed {
        let cell = p.push_record(
            Record::new(tag::CELL, *cell_id)
                .zsub(tag::EDID, &format!("Cell{cell_id:X}"))
                .sub(b"DATA", [1u8, 0]),
        );
        let mut temporary = Group::new(GroupKind::CellTemporary(*cell_id));
        for (object, deleted) in refs {
            let mut record = Record::new(tag::REFR, *object)
                .sub(b"NAME", 0u32.to_le_bytes())
                .zsub(tag::EDID, label);
            if *deleted {
                record = record.with_flags(flags::DELETED);
            }
            temporary.entries.push(Entry::Record(p.push_record(record)));
        }
        let mut children = Group::new(GroupKind::CellChildren(*cell_id));
        children.entries.push(Entry::Group(temporary));
        sub.entries.push(Entry::Record(cell));
        sub.entries.push(Entry::Group(children));
    }
    let mut block = Group::new(GroupKind::InteriorBlock(0));
    block.entries.push(Entry::Group(sub));
    let mut top = Group::new(GroupKind::Top(tag::CELL));
    top.entries.push(Entry::Group(block));
    p.groups.push(top);
    p
}

proptest! {
    #![proptest_config(ProptestConfig { cases: 128, ..ProptestConfig::default() })]

    /// Every reference the index files under a cell is the one the plan put
    /// there last, and a deleted winner moves to the deleted list rather than
    /// disappearing.
    #[test]
    fn the_cell_index_holds_what_the_last_writer_placed(
        (refs, patches) in cell_order_strategy()
    ) {
        // The master puts every reference in cell A, alive.
        let mut plan: Vec<(u32, bool)> = (0..refs).map(|_| (CELL_A, false)).collect();
        let mut master_cells: BTreeMap<u32, Vec<(u32, bool)>> = BTreeMap::new();
        master_cells.insert(CELL_A, (0..refs).map(|r| (FIRST_REF + r as u32, false)).collect());
        master_cells.entry(CELL_B).or_default();

        let mut order = LoadOrder::new();
        let master = round_tripped(&cells_plugin(
            FileHeader { flags: flags::MASTER, ..Default::default() },
            "m",
            &master_cells,
        ))?;
        order.add("Master.esm", master)
            .map_err(|e| TestCaseError::fail(format!("master did not load: {e}")))?;

        for (i, moves) in patches.iter().enumerate() {
            let mut cells: BTreeMap<u32, Vec<(u32, bool)>> = BTreeMap::new();
            let mut touched = false;
            for (r, action) in moves.iter().enumerate() {
                if let Some((to_b, deleted)) = action {
                    let cell = if *to_b { CELL_B } else { CELL_A };
                    plan[r] = (cell, *deleted);
                    cells.entry(cell).or_default().push((FIRST_REF + r as u32, *deleted));
                    touched = true;
                }
            }
            if !touched {
                continue;
            }
            // Every cell the patch writes into needs its record present.
            for cell in [CELL_A, CELL_B] {
                if cells.contains_key(&cell) {
                    cells.entry(cell).or_default();
                }
            }
            let plugin = round_tripped(&cells_plugin(
                FileHeader { masters: vec!["Master.esm".into()], ..Default::default() },
                &format!("p{i}"),
                &cells,
            ))?;
            order.add(&format!("Patch{i}.esp"), plugin)
                .map_err(|e| TestCaseError::fail(format!("Patch{i} did not load: {e}")))?;
        }

        let index = order.build_cell_index();
        let replay = common::repro(KRATE, FILE, "the_cell_index_holds_what_the_last_writer_placed");

        for cell_raw in [CELL_A, CELL_B] {
            let cell = GlobalFormId { file: 0, object: cell_raw };
            let mut want_live = BTreeSet::new();
            let mut want_dead = BTreeSet::new();
            for (r, (where_it_is, deleted)) in plan.iter().enumerate() {
                if *where_it_is != cell_raw {
                    continue;
                }
                let id = GlobalFormId { file: 0, object: FIRST_REF + r as u32 };
                if *deleted { want_dead.insert(id); } else { want_live.insert(id); }
            }
            let got_live: BTreeSet<_> = index.references(cell).iter().copied().collect();
            let got_dead: BTreeSet<_> = index.deleted_references(cell).iter().copied().collect();
            prop_assert_eq!(
                got_live, want_live,
                "live references in cell {:X}. Replay: {}", cell_raw, replay
            );
            prop_assert_eq!(
                got_dead, want_dead,
                "deleted references in cell {:X}. Replay: {}", cell_raw, replay
            );
        }
    }
}
