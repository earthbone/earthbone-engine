//! Synthetic NX fixtures following VGAudio's standard writer.
//! Packets encode three 20 ms sine frames with libopus 1.6, application audio,
//! 32 kbit/s per channel, default VBR. Mono is 440 Hz at 48 kHz. Stereo is
//! 440 Hz left and 880 Hz right at 24 kHz, both at amplitude 0.5.
//! Tests construct their own NX and FUZ containers and need no external tool.

use super::decode;
use crate::{fuz, Container, Error, SoundSource};
use soe_bsa::Vfs;

fn fixture(packets: &[&[u8]], rate: u32, channels: u8, skip: u32) -> Vec<u8> {
    let mut data = Vec::new();
    for packet in packets {
        data.extend_from_slice(&(packet.len() as u32).to_be_bytes());
        data.extend_from_slice(&0u32.to_be_bytes());
        data.extend_from_slice(packet);
    }
    let mut nx = Vec::new();
    nx.extend_from_slice(&0x8000_0001u32.to_le_bytes());
    nx.extend_from_slice(&24u32.to_le_bytes());
    nx.extend_from_slice(&[0, channels, 8, 0]);
    nx.extend_from_slice(&rate.to_le_bytes());
    nx.extend_from_slice(&32u32.to_le_bytes());
    nx.extend_from_slice(&[0; 8]);
    nx.extend_from_slice(&skip.to_le_bytes());
    nx.extend_from_slice(&0x8000_0004u32.to_le_bytes());
    nx.extend_from_slice(&(data.len() as u32).to_le_bytes());
    nx.extend_from_slice(&data);
    let mut wrapper = fuz::NX_OPUS_SIGNATURE.to_vec();
    wrapper.extend_from_slice(&60u32.to_le_bytes());
    wrapper.extend_from_slice(&u32::from(channels).to_le_bytes());
    wrapper.extend_from_slice(&20u32.to_le_bytes());
    wrapper.extend_from_slice(&(nx.len() as u32).to_le_bytes());
    wrapper.extend_from_slice(&nx);
    wrapper
}

#[test]
fn aud_03_nx_opus_fuz_decodes_to_pcm_and_preserves_lip() {
    let vfs = Vfs::new();
    let payload = fixture(MONO, 48_000, 1, MONO_SKIP);
    let bytes = fuz::write(1, &[1, 2, 3], &payload);
    let sound = SoundSource::new(&vfs).decode(&bytes).unwrap();
    assert_eq!(sound.container, Container::Fuz);
    assert_eq!(sound.lip.as_deref(), Some(&[1, 2, 3][..]));
    assert_eq!(sound.pcm.sample_rate, 48_000);
    assert_eq!(sound.pcm.channels, 1);
    assert_eq!(sound.pcm.frames(), 2880 - MONO_SKIP as usize);
    assert!(sound.pcm.samples.iter().all(|s| s.is_finite()));
    assert!(sound.pcm.peak() > 0.1 && sound.pcm.peak() < 1.0);
}

#[test]
fn stereo_keeps_channel_order_and_native_sample_rate() {
    let pcm = decode(&fixture(STEREO, 24_000, 2, STEREO_SKIP)).unwrap();
    assert_eq!(pcm.sample_rate, 24_000);
    assert_eq!(pcm.channels, 2);
    assert_eq!(pcm.frames(), 1440 - STEREO_SKIP as usize);
    assert!(pcm.samples.iter().all(|s| s.is_finite()));
    for (channel, frequency) in [(0, 440.0_f32), (1, 880.0)] {
        let projection = |hz: f32| {
            let mut sin = 0.0;
            let mut cos = 0.0;
            for (i, frame) in pcm.samples.as_chunks::<2>().0.iter().enumerate().skip(240) {
                let phase = std::f32::consts::TAU * hz * i as f32 / 24_000.0;
                sin += frame[channel] * phase.sin();
                cos += frame[channel] * phase.cos();
            }
            sin.hypot(cos)
        };
        let expected = projection(frequency);
        assert!(expected > 50.0, "channel {channel}: amplitude {expected}");
        assert!(expected > 5.0 * projection(1320.0 - frequency));
    }
}

#[test]
fn encoder_delay_can_span_packets_without_resetting_the_decoder() {
    let untrimmed = decode(&fixture(MONO, 48_000, 1, 0)).unwrap();
    let trimmed = decode(&fixture(MONO, 48_000, 1, 1200)).unwrap();
    assert_eq!(trimmed.samples, untrimmed.samples[1200..]);
}

#[test]
fn rounded_wrapper_duration_does_not_truncate_packet_samples() {
    let mut bytes = fixture(MONO, 48_000, 1, MONO_SKIP);
    bytes[4..8].copy_from_slice(&1u32.to_le_bytes());
    assert_eq!(decode(&bytes).unwrap().frames(), 2880 - MONO_SKIP as usize);
}

#[test]
fn every_truncated_prefix_returns_a_typed_error() {
    let bytes = fixture(MONO, 48_000, 1, MONO_SKIP);
    for end in 0..bytes.len() {
        assert!(
            matches!(decode(&bytes[..end]), Err(Error::Truncated { .. })),
            "prefix {end}"
        );
    }
}

#[test]
fn invalid_headers_offsets_and_lengths_are_rejected() {
    let original = fixture(MONO, 48_000, 1, MONO_SKIP);
    for (offset, value) in [
        (0, 0),
        (8, 0),
        (8, 3),
        (8, 2),
        (12, 19),
        (16, u32::MAX),
        (20, 0),
        (24, 23),
        (32, 44_100),
        (36, 0),
        (36, u32::MAX),
        (48, u32::MAX),
        (52, 0),
        (56, u32::MAX),
        (56, 0),
        (60, 0),
        (60, u32::MAX),
    ] {
        let mut bytes = original.clone();
        bytes[offset..offset + 4].copy_from_slice(&value.to_le_bytes());
        assert!(
            matches!(
                decode(&bytes),
                Err(Error::Malformed { .. } | Error::Truncated { .. })
            ),
            "offset {offset}, value {value}"
        );
    }
    let mut bytes = original;
    bytes[28] = 1;
    assert!(matches!(decode(&bytes), Err(Error::Malformed { .. })));
}

#[test]
fn malformed_packet_and_partial_packet_header_are_errors() {
    assert!(matches!(
        decode(&fixture(&[&[0xff]], 48_000, 1, 0)),
        Err(Error::Decode(_))
    ));
    let mut bytes = fixture(MONO, 48_000, 1, 0);
    bytes.push(0);
    let payload_size = (bytes.len() - 20) as u32;
    let data_size = (bytes.len() - 60) as u32;
    bytes[16..20].copy_from_slice(&payload_size.to_le_bytes());
    bytes[56..60].copy_from_slice(&data_size.to_le_bytes());
    assert!(matches!(decode(&bytes), Err(Error::Truncated { .. })));
}

#[test]
fn empty_stream_and_excess_encoder_delay_are_errors() {
    assert!(matches!(
        decode(&fixture(&[], 48_000, 1, 0)),
        Err(Error::Malformed { .. })
    ));
    assert!(matches!(
        decode(&fixture(MONO, 48_000, 1, 3000)),
        Err(Error::Malformed { .. })
    ));
}

#[test]
fn repeated_tiny_packets_stop_at_the_decoded_pcm_limit() {
    let silence: &[u8] = &[0xf8, 0xff, 0xfe];
    let budget = 2 * 960 * std::mem::size_of::<f32>();
    let at_limit = fixture(&[silence; 2], 48_000, 1, 0);
    let pcm = super::decode_with_limit(&at_limit, budget).unwrap();
    assert_eq!(pcm.frames(), 1920);
    assert!(pcm.samples.capacity() * std::mem::size_of::<f32>() <= budget);
    let over_limit = fixture(&[silence; 3], 48_000, 1, 0);
    let error = super::decode_with_limit(&over_limit, budget).unwrap_err();
    assert!(matches!(error, Error::Decode(ref why) if why.contains("PCM exceeds byte limit")));
}

