//! `plugins.txt` and `loadorder.txt`.
//!
//! Skyrim SE's `plugins.txt` lists plugins one per line, an asterisk in front
//! of the active ones, `#` lines as comments. The game keeps it under
//! `%LOCALAPPDATA%\Skyrim Special Edition\`, MO2 keeps one per profile.
//! `loadorder.txt` is the manager convention (MO2, LOOT) for the order of
//! every plugin including the disabled ones, bare names, no prefix.

use std::path::Path;

use crate::error::{Error, Result};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PluginLine {
    pub name: String,
    pub enabled: bool,
}

fn clean(text: &str) -> impl Iterator<Item = &str> {
    text.strip_prefix('\u{feff}')
        .unwrap_or(text)
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
}

pub fn parse_plugins_txt(text: &str) -> Vec<PluginLine> {
    clean(text)
        .map(|line| match line.strip_prefix('*') {
            Some(name) => PluginLine {
                name: name.trim().to_string(),
                enabled: true,
            },
            None => PluginLine {
                name: line.to_string(),
                enabled: false,
            },
        })
        .collect()
}

pub fn parse_loadorder_txt(text: &str) -> Vec<String> {
    clean(text)
        .map(|l| l.strip_prefix('*').unwrap_or(l).trim().to_string())
        .collect()
}

/// An absent file is an empty list, since a fresh install has none.
pub fn read_plugins_txt(path: &Path) -> Result<Vec<PluginLine>> {
    match std::fs::read_to_string(path) {
        Ok(text) => Ok(parse_plugins_txt(&text)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Vec::new()),
        Err(source) => Err(Error::Io {
            path: path.to_path_buf(),
            source,
        }),
    }
}

pub fn read_loadorder_txt(path: &Path) -> Result<Vec<String>> {
    match std::fs::read_to_string(path) {
        Ok(text) => Ok(parse_loadorder_txt(&text)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Vec::new()),
        Err(source) => Err(Error::Io {
            path: path.to_path_buf(),
            source,
        }),
    }
}

/// CRLF line ends, as the game and MO2 write.
pub fn render_plugins_txt(lines: &[PluginLine]) -> String {
    let mut out = String::from(
        "# This file is used by the game to keep track of your downloaded content.\r\n",
    );
    for l in lines {
        if l.enabled {
            out.push('*');
        }
        out.push_str(&l.name);
        out.push_str("\r\n");
    }
    out
}

pub fn render_loadorder_txt(names: &[String]) -> String {
    let mut out = String::from(
        "# This file was generated by soe-profile and lists every plugin in order.\r\n",
    );
    for n in names {
        out.push_str(n);
        out.push_str("\r\n");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn asterisk_marks_active_and_comments_are_skipped() {
        let text = "\u{feff}# generated\r\n*Skyrim.esm\r\nDisabled.esp\r\n  *Spaced.esp  \r\n\r\n";
        let lines = parse_plugins_txt(text);
        assert_eq!(
            lines,
            vec![
                PluginLine {
                    name: "Skyrim.esm".into(),
                    enabled: true
                },
                PluginLine {
                    name: "Disabled.esp".into(),
                    enabled: false
                },
                PluginLine {
                    name: "Spaced.esp".into(),
                    enabled: true
                },
            ]
        );
        assert_eq!(
            parse_loadorder_txt("# x\nA.esm\n*B.esp\n"),
            vec!["A.esm", "B.esp"]
        );
    }

    #[test]
    fn renders_round_trip() {
        let lines = parse_plugins_txt("*A.esm\nB.esp\n");
        let text = render_plugins_txt(&lines);
        assert!(text.starts_with("# "));
        assert!(text.contains("*A.esm\r\nB.esp\r\n"));
        assert_eq!(parse_plugins_txt(&text), lines);
        let names = vec!["A.esm".to_string(), "B.esp".to_string()];
        assert_eq!(parse_loadorder_txt(&render_loadorder_txt(&names)), names);
    }

    #[test]
    fn a_missing_file_is_an_empty_list() {
        let dir = tempfile::tempdir().unwrap();
        assert!(read_plugins_txt(&dir.path().join("plugins.txt"))
            .unwrap()
            .is_empty());
        assert!(read_loadorder_txt(&dir.path().join("loadorder.txt"))
            .unwrap()
            .is_empty());
    }
}
